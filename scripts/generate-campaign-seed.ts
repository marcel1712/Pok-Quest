/**
 * Validates the campaign content under src/features/journey/content/ and prints an
 * idempotent SQL seed for `campaign_regions` / `campaign_nodes` /
 * `campaign_node_prerequisites` to stdout. Offline admin script, never run by the app.
 * Put the output in a new migration (`npx supabase migration new seed_campaign_...`)
 * and apply it with `npm run db:push`.
 *
 * Run with: npm run campaign:seed
 */
import type { CampaignRegionContent } from '../src/features/journey/content/schema.ts'
import { sinnoh } from '../src/features/journey/content/sinnoh.ts'
import { validateCampaignRegion } from '../src/features/journey/content/validate.ts'

const REGIONS: CampaignRegionContent[] = [sinnoh]

function text(value: string | undefined): string {
  return value === undefined ? 'null' : `'${value.replaceAll("'", "''")}'`
}

function regionSeed(region: CampaignRegionContent, sortOrder: number): string {
  const nodeRows = region.nodes.map(
    (node, index) =>
      `  (${[
        text(node.id),
        text(region.id),
        index + 1,
        text(node.kind),
        text(node.title),
        text(node.summary),
        text(node.npcName),
        text(node.encounter.kind),
        node.encounter.difficulty,
        node.requiredVictories,
        node.repeatable,
      ].join(', ')})`,
  )
  const prerequisiteRows = region.nodes.flatMap((node) =>
    node.requires.map((requiredId) => `  (${text(node.id)}, ${text(requiredId)})`),
  )

  return `-- Region "${region.id}", content version ${region.contentVersion}.
insert into public.campaign_regions (id, name, sort_order, content_version) values
  (${text(region.id)}, ${text(region.name)}, ${sortOrder}, ${region.contentVersion})
on conflict (id) do update set
  name = excluded.name,
  sort_order = excluded.sort_order,
  content_version = excluded.content_version;

insert into public.campaign_nodes (id, region_id, sort_order, kind, title, summary, npc_name, encounter_kind, encounter_difficulty, required_victories, repeatable) values
${nodeRows.join(',\n')}
on conflict (id) do update set
  region_id = excluded.region_id,
  sort_order = excluded.sort_order,
  kind = excluded.kind,
  title = excluded.title,
  summary = excluded.summary,
  npc_name = excluded.npc_name,
  encounter_kind = excluded.encounter_kind,
  encounter_difficulty = excluded.encounter_difficulty,
  required_victories = excluded.required_victories,
  repeatable = excluded.repeatable;

delete from public.campaign_node_prerequisites
  where node_id in (select id from public.campaign_nodes where region_id = ${text(region.id)});
${
  prerequisiteRows.length > 0
    ? `insert into public.campaign_node_prerequisites (node_id, requires_node_id) values\n${prerequisiteRows.join(',\n')};`
    : ''
}
`
}

const problems = REGIONS.flatMap((region) =>
  validateCampaignRegion(region).map((issue) => `[${region.id}] ${issue}`),
)
if (problems.length > 0) {
  console.error(`Campaign content is invalid:\n${problems.join('\n')}`)
  process.exit(1)
}

console.log(
  `-- Generated by \`npm run campaign:seed\` from src/features/journey/content/. Do not\n` +
    `-- edit by hand: change the content, bump its contentVersion and regenerate into a\n` +
    `-- new migration. Nodes are never deleted here — removing one that players already\n` +
    `-- have progress on needs its own reviewed migration.\n`,
)
console.log(REGIONS.map((region, index) => regionSeed(region, index + 1)).join('\n'))
