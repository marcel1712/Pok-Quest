/**
 * Runs every database verification against the linked Supabase project and reports a
 * pass/fail per script (T-036):
 *   - each supabase/verification/*.sql;
 *   - a generated "rule parity" check: the numbers in tests/fixtures/rule-parity.json,
 *     which the TypeScript engine is also unit-tested against, must be exactly what the
 *     SQL triggers and functions produce.
 *
 * Every one of them runs inside a subtransaction that is always rolled back, so this is
 * safe against the single (production) environment — but it does need the Supabase CLI
 * to be logged in and linked, which is why it is a manual command and not part of CI.
 *
 * Run with: npm run db:verify
 */
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

type Fixture = {
  commitments: {
    encounterDifficulty: number
    partyLevels: number[]
    minTaskDifficulty: number
    minFocusMinutes: number
  }[]
  xpCurve: { level: number; totalXp: number }[]
  taskXp: { difficulty: number; full: number; diminished: number }[]
  focusXp: { minutes: number; xp: number }[]
  taskFullRewardsPerDay: number
}

const VERIFICATION_DIR = 'supabase/verification'

function rows(values: (number | string)[][]): string {
  return values.map((row) => `(${row.join(', ')})`).join(',\n      ')
}

function paritySql(fixture: Fixture): string {
  const commitments = fixture.commitments.map((c) => [
    c.encounterDifficulty,
    `array[${c.partyLevels.join(', ')}]::integer[]`,
    c.minTaskDifficulty,
    c.minFocusMinutes,
  ])

  return `-- Generated by scripts/run-db-verification.ts from tests/fixtures/rule-parity.json.
do $$
declare
  test_owner uuid;
  c record;
  node_id text;
  task_id uuid;
  session_id uuid;
  battle_id uuid;
  amount integer;
  got_error boolean;
  i integer;
begin
  select id into test_owner from auth.users limit 1;

  begin
    perform set_config('request.jwt.claims', json_build_object('sub', test_owner)::text, true);
    update public.focus_sessions set status = 'cancelled', ended_at = now()
      where owner_id = test_owner and status in ('running', 'paused');
    -- Every node completed: each repeatable route can then be fought, at its difficulty.
    delete from public.campaign_node_progress where owner_id = test_owner;
    insert into public.campaign_node_progress (owner_id, node_id, victories, completed_at)
      select test_owner, id, required_victories, now() from public.campaign_nodes;

    -- 1. XP curve.
    for c in select * from (values
      ${rows(fixture.xpCurve.map((x) => [x.level, x.totalXp]))}
    ) as t(level, total_xp) loop
      if public.total_xp_for_level(c.level) != c.total_xp then
        raise exception 'FAIL: total_xp_for_level(%) = %, fixture says %', c.level, public.total_xp_for_level(c.level), c.total_xp;
      end if;
    end loop;

    -- 2. Minimum commitment per encounter difficulty and party: one below the fixture's
    --    minimum must be refused, the minimum itself accepted — for tasks and for focus.
    for c in select * from (values
      ${rows(commitments)}
    ) as t(difficulty, party_levels, min_task, min_focus) loop
      update public.owned_pokemon set party_position = null where owner_id = test_owner;
      for i in 1..coalesce(array_length(c.party_levels, 1), 0) loop
        insert into public.owned_pokemon (owner_id, pokedex_number, level, xp, party_position)
          values (test_owner, 396, c.party_levels[i], public.total_xp_for_level(c.party_levels[i]), i);
      end loop;

      select n.id into node_id from public.campaign_nodes n
        where n.repeatable and n.encounter_kind = 'wild' and n.encounter_difficulty = c.difficulty
        order by n.sort_order limit 1;
      if node_id is null then
        raise exception 'FAIL: no repeatable wild node with difficulty %', c.difficulty;
      end if;

      insert into public.tasks (owner_id, title, difficulty)
        values (test_owner, '__parity_commitment__', 5) returning id into task_id;
      if c.min_task > 1 then
        got_error := false;
        begin
          insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_difficulty, task_id, campaign_node_id)
            values (test_owner, 'wild', 1, 'task', c.min_task - 1, task_id, node_id);
        exception when check_violation then got_error := true;
        end;
        if not got_error then
          raise exception 'FAIL: difficulty % party % accepted a task commitment of %, fixture minimum is %', c.difficulty, c.party_levels, c.min_task - 1, c.min_task;
        end if;
      end if;
      insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_difficulty, task_id, campaign_node_id)
        values (test_owner, 'wild', 1, 'task', c.min_task, task_id, node_id);

      insert into public.focus_sessions (owner_id, planned_duration_seconds, status, started_at, ended_at)
        values (test_owner, 600, 'cancelled', now(), now()) returning id into session_id;
      if c.min_focus > 1 then
        got_error := false;
        begin
          insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_duration_minutes, focus_session_id, campaign_node_id)
            values (test_owner, 'wild', 1, 'focusSession', c.min_focus - 1, session_id, node_id);
        exception when check_violation then got_error := true;
        end;
        if not got_error then
          raise exception 'FAIL: difficulty % party % accepted a focus commitment of % min, fixture minimum is %', c.difficulty, c.party_levels, c.min_focus - 1, c.min_focus;
        end if;
      end if;
      insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_duration_minutes, focus_session_id, campaign_node_id)
        values (test_owner, 'wild', 1, 'focusSession', c.min_focus, session_id, node_id);
    end loop;

    -- From here on the party is empty, so XP is the bare formula (no team multiplier).
    update public.owned_pokemon set party_position = null where owner_id = test_owner;

    -- 3. Task XP: paid in full for the first ${fixture.taskFullRewardsPerDay} of the day, diminished after.
    for c in select * from (values
      ${rows(fixture.taskXp.map((x) => [x.difficulty, x.full, x.diminished]))}
    ) as t(difficulty, full_xp, diminished_xp) loop
      delete from public.reward_events where owner_id = test_owner;
      for i in 1..${fixture.taskFullRewardsPerDay + 1} loop
        insert into public.tasks (owner_id, title, difficulty)
          values (test_owner, '__parity_task_xp__', c.difficulty) returning id into task_id;
        insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_difficulty, task_id)
          values (test_owner, 'trainer', 1, 'task', 1, task_id) returning id into battle_id;
        update public.tasks set status = 'completed', completed_at = clock_timestamp() where id = task_id;
        select re.amount into amount from public.reward_events re where re.source_id = battle_id;

        if i = 1 and amount is distinct from c.full_xp then
          raise exception 'FAIL: difficulty-% task paid % XP, fixture says %', c.difficulty, amount, c.full_xp;
        end if;
        if i = ${fixture.taskFullRewardsPerDay + 1} and amount is distinct from c.diminished_xp then
          raise exception 'FAIL: difficulty-% task past the daily count paid % XP, fixture says %', c.difficulty, amount, c.diminished_xp;
        end if;
      end loop;
    end loop;

    -- 4. Focus XP.
    for c in select * from (values
      ${rows(fixture.focusXp.map((x) => [x.minutes, x.xp]))}
    ) as t(minutes, xp) loop
      insert into public.focus_sessions (owner_id, planned_duration_seconds, status, started_at)
        values (test_owner, c.minutes * 60, 'running', now()) returning id into session_id;
      insert into public.battles (owner_id, encounter_kind, encounter_difficulty, commitment_type, commitment_min_duration_minutes, focus_session_id)
        values (test_owner, 'trainer', 1, 'focusSession', 1, session_id) returning id into battle_id;
      update public.focus_sessions set status = 'completed', ended_at = now() where id = session_id;
      select re.amount into amount from public.reward_events re where re.source_id = battle_id;
      if amount is distinct from c.xp then
        raise exception 'FAIL: a %-minute session paid % XP, fixture says %', c.minutes, amount, c.xp;
      end if;
    end loop;

    raise exception 'PARITY_ROLLBACK';
  exception when others then
    if sqlerrm = 'PARITY_ROLLBACK' then
      raise notice 'PASS: database rules match the fixture (rolled back)';
    else
      raise;
    end if;
  end;
end $$;
`
}

function runSqlFile(path: string): { ok: boolean; detail: string } {
  const result = spawnSync('npx', ['supabase', 'db', 'query', '--linked', '-f', `"${path}"`], {
    shell: true,
    encoding: 'utf8',
  })
  const output = `${result.stdout ?? ''}\n${result.stderr ?? ''}`
  const failed = result.status !== 0 || output.includes('"_tag":"Error"') || /ERROR:/.test(output)
  if (!failed) return { ok: true, detail: '' }

  // The CLI wraps the Postgres error in JSON, with its newlines escaped.
  const message =
    /ERROR:\s*(.*?)(?:\\n|\n|$)/.exec(output)?.[1]?.trim() ?? output.trim().slice(0, 400)
  return { ok: false, detail: message }
}

const temporaryDir = mkdtempSync(join(tmpdir(), 'pokequest-verify-'))
let failures = 0

try {
  const fixture = JSON.parse(readFileSync('tests/fixtures/rule-parity.json', 'utf8')) as Fixture
  const parityPath = join(temporaryDir, 'rule-parity.sql')
  writeFileSync(parityPath, paritySql(fixture))

  const scripts = [
    ...readdirSync(VERIFICATION_DIR)
      .filter((name) => name.endsWith('.sql'))
      .sort()
      .map((name) => ({ name, path: join(VERIFICATION_DIR, name) })),
    { name: 'rule-parity (generated from tests/fixtures/rule-parity.json)', path: parityPath },
  ]

  for (const script of scripts) {
    const { ok, detail } = runSqlFile(script.path)
    console.log(`${ok ? 'PASS' : 'FAIL'}  ${script.name}${ok ? '' : `\n      ${detail}`}`)
    if (!ok) failures++
  }

  console.log(
    failures === 0
      ? `\nAll ${scripts.length} database checks passed.`
      : `\n${failures} of ${scripts.length} database checks FAILED.`,
  )
} finally {
  rmSync(temporaryDir, { recursive: true, force: true })
}

process.exit(failures === 0 ? 0 : 1)
